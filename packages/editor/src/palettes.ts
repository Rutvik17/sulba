// The editor's colour themes, as data. Sulba's own follows the page's light or dark theme through
// the design tokens; each of the others follows the colours of the editor theme it is named after.
// themes.ts draws them in CodeMirror; the theme panel shows them without loading CodeMirror.

export interface Palette {
  readonly id: string;
  readonly name: string;
  /** light or dark: which group the theme is listed in. Sulba's follows the page. */
  readonly kind: 'light' | 'dark' | 'page';
  readonly bg: string;
  readonly fg: string;
  /** Line numbers. */
  readonly ln: string;
  readonly cursor: string;
  readonly sel: string;
  readonly kw: string;
  /** Function names. */
  readonly fn: string;
  /** Classes, built-in constants and types. */
  readonly bi: string;
  readonly str: string;
  readonly num: string;
  readonly com: string;
  readonly op: string;
  /** Attributes after a dot. */
  readonly prop: string;
  readonly boldKeywords?: boolean;
  readonly italicComments?: boolean;
}

